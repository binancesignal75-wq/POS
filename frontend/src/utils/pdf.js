/**
 * PDFs — upar dukan ka logo aur naam
 */
import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { asset, toDataUrl } from '../api';
import { initials, monthName, num } from './format';

const GREEN = [60, 157, 20];

async function header(doc, store, title, sub) {
  const logo = await toDataUrl(asset(store.logo_url));
  if (logo) {
    try {
      const fmt = logo.includes('image/png') ? 'PNG' : logo.includes('image/webp') ? 'WEBP' : 'JPEG';
      doc.addImage(logo, fmt, 15, 13, 20, 20);
    } catch { /* logo nahi laga to initials */ }
  } else {
    doc.setFillColor(...GREEN); doc.roundedRect(15, 13, 20, 20, 3, 3, 'F');
    doc.setTextColor(255); doc.setFont('helvetica', 'bold'); doc.setFontSize(12);
    doc.text(initials(store.name), 25, 25, { align: 'center' });
  }
  doc.setTextColor(16, 24, 40); doc.setFont('helvetica', 'bold'); doc.setFontSize(16);
  doc.text(store.name, 39, 21);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9.5); doc.setTextColor(100);
  doc.text([store.address, store.city, store.phone && `Ph ${store.phone}`].filter(Boolean).join('  ·  ') || ' ', 39, 28);
  doc.setTextColor(...GREEN); doc.setFont('helvetica', 'bold'); doc.setFontSize(11);
  doc.text(title, 195, 21, { align: 'right' });
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(100);
  doc.text(sub, 195, 28, { align: 'right' });
  doc.setDrawColor(...GREEN); doc.setLineWidth(0.6); doc.line(15, 37, 195, 37);
}

function footer(doc) {
  const n = doc.getNumberOfPages();
  for (let i = 1; i <= n; i++) {
    doc.setPage(i);
    doc.setFontSize(8); doc.setTextColor(140);
    doc.text('Generated by TYPOS POS', 15, 288);
    doc.text(`Page ${i} of ${n}`, 195, 288, { align: 'right' });
  }
}

const today = () => new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'long', year: 'numeric' });
const fileName = (store, what) => `${store.name.replace(/[^\w]+/g, '-')}-${what}-${new Date().toISOString().slice(0, 10)}.pdf`;

/** rows: [{name, strength, company, stock, order_qty}] */
export async function lowStockPdf(store, rows) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  await header(doc, store, 'LOW STOCK LIST', today());
  doc.setFontSize(10); doc.setTextColor(70);
  doc.text('Neeche di gayi dawaiyan khatam ya kam hain. Barah-e-karam ye quantity bhej dein.', 15, 45);
  autoTable(doc, {
    startY: 50,
    head: [['#', 'Dawai', 'Strength', 'Company', 'Baqi', 'Mangwana']],
    body: rows.map((r, i) => [i + 1, r.name, r.strength || '-', r.company || '-', r.stock, r.order_qty]),
    theme: 'grid',
    headStyles: { fillColor: [241, 245, 249], textColor: [51, 65, 85], fontStyle: 'bold' },
    styles: { fontSize: 9.5, cellPadding: 2.6, lineColor: [226, 232, 240] },
    columnStyles: { 0: { cellWidth: 10 }, 4: { halign: 'center' }, 5: { halign: 'center', fontStyle: 'bold' } },
    didParseCell: (d) => { if (d.section === 'body' && d.column.index === 4 && Number(d.cell.raw) <= 0) d.cell.styles.textColor = [220, 38, 38]; }
  });
  const y = doc.lastAutoTable.finalY + 8;
  doc.setFontSize(10); doc.setTextColor(30);
  doc.text(`Kul dawaiyan: ${rows.length}    Kul packs: ${num(rows.reduce((a, r) => a + Number(r.order_qty || 0), 0))}`, 15, y);
  footer(doc);
  doc.save(fileName(store, 'low-stock'));
}

export async function monthPdf(store, r) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  await header(doc, store, 'MONTHLY RECORD', monthName(r.ym));
  const pk = (v) => 'Rs ' + Math.round(v).toLocaleString('en-PK');
  autoTable(doc, {
    startY: 46,
    head: [['', monthName(r.ym)]],
    body: [
      ['Kul sale', pk(r.sale)],
      ['Profit', pk(r.profit)],
      ['Bills', num(r.bills)],
      ['Dawaiyan biki (stock gaya)', `${num(r.items_sold)} packs`],
      ['Stock aaya (purchase)', `${pk(r.stock_in_value)} · ${num(r.stock_in_qty)} packs`],
      ['Sab se zyada biki', r.top_product || '-'],
      ['Pichle mahine se', r.change_pct === null ? '-' : `${r.change_pct >= 0 ? '+' : ''}${r.change_pct.toFixed(1)}%`]
    ],
    theme: 'grid',
    headStyles: { fillColor: GREEN, textColor: 255 },
    styles: { fontSize: 11, cellPadding: 4 },
    columnStyles: { 0: { fontStyle: 'bold', cellWidth: 80 } }
  });
  footer(doc);
  doc.save(fileName(store, r.ym));
}

